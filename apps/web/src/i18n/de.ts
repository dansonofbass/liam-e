const subjectText = (subject: string) => String(subject).trim() ? String(subject) : de.mail.noSubject
const noticeSubject = (subject: string) => {
  const text = subjectText(subject)
  return text.length > 60 ? `${text.slice(0, 59).trimEnd()}…` : text
}

