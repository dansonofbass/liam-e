"""The shipped migrations against a live Postgres: they apply, they match the models, and they revert.

The offline suite proves every model table has a revision; only a server can prove the revision
builds the table the model describes. Each run migrates a scratch database to ``heads`` and asks
Alembic's own ``check`` whether autogenerate would still emit anything, which is exactly the drift a
hand-shipped baseline can accumulate against its model.

Runs under the same gate as the other contract suites -- ``RUN_PG_CONTRACT=1`` plus a reachable
``DATABASE_URL`` (``bunx nx run db:test-pg-contract``); skipped otherwise.
"""

import asyncio
import logging
import os
import uuid
from collections.abc import Iterator
from pathlib import Path

import db.models  # noqa: F401  (import populates SQLModel.metadata)
import env.db
import pytest
from alembic import command
from alembic.config import Config
from db import metadata
from sqlalchemy import text
from sqlalchemy.engine import make_url
from sqlalchemy.ext.asyncio import create_async_engine

pytestmark = pytest.mark.skipif(not os.getenv("RUN_PG_CONTRACT"), reason="RUN_PG_CONTRACT is not set")

PROJECT = Path(__file__).resolve().parents[1]


async def _admin(statement: str) -> None:
    engine = create_async_engine(env.db.env.async_database_url, isolation_level="AUTOCOMMIT")
    try:
        async with engine.connect() as connection:
            await connection.execute(text(statement))
    finally:
        await engine.dispose()


async def _admin_on(url: str, statement: str) -> None:
    engine = create_async_engine(url)
    try:
        async with engine.begin() as connection:
            await connection.execute(text(statement))
    finally:
        await engine.dispose()


async def _scalar(url: str, statement: str) -> object:
    engine = create_async_engine(url)
    try:
        async with engine.connect() as connection:
            return await connection.scalar(text(statement))
    finally:
        await engine.dispose()


@pytest.fixture
def scratch(monkeypatch: pytest.MonkeyPatch) -> Iterator[tuple[Config, str]]:
    """An Alembic config pointed at a throwaway database, dropped again on the way out."""
    name = f"migrations_{uuid.uuid4().hex[:12]}"
    asyncio.run(_admin(f'CREATE DATABASE "{name}"'))
    url = make_url(env.db.env.async_database_url).set(database=name).render_as_string(hide_password=False)
    config = Config(str(PROJECT / "alembic.ini"))
    config.set_main_option("script_location", str(PROJECT / "src" / "db" / "migrations"))
    config.set_main_option("prepend_sys_path", str(PROJECT / "src"))
    # env.py reads the URL from settings, not alembic.ini; point that at the scratch database.
    monkeypatch.setattr(env.db.env, "database_url", url)
    try:
        yield config, url
    finally:
        monkeypatch.undo()
        asyncio.run(_admin(f'DROP DATABASE IF EXISTS "{name}" WITH (FORCE)'))


def test_the_shipped_migrations_build_exactly_the_model_schema(scratch: tuple[Config, str]) -> None:
    config, url = scratch
    command.upgrade(config, "heads")
    # A table the app does not own, as a library or extension would leave one: autogenerate must not
    # propose dropping it.
    asyncio.run(_admin_on(url, "CREATE TABLE library_owned_probe (id integer PRIMARY KEY)"))

    command.check(config)  # raises AutoGenerateDiffsDetected on any drift


def test_suggestion_check_removal_and_other_checks_are_drift_free(scratch):
    config, url = scratch
    command.upgrade(config, "heads")
    assert asyncio.run(_scalar(url, "SELECT count(*) FROM pg_constraint WHERE contype = 'c' AND conrelid = 'personalization_settings'::regclass")) == 0
    command.check(config)


def test_downgrade_to_base_removes_every_model_table(scratch: tuple[Config, str]) -> None:
    config, url = scratch
    command.upgrade(config, "heads")
    command.downgrade(config, "base")

    for table in metadata.tables:
        assert asyncio.run(_scalar(url, f"SELECT to_regclass('public.{table}')")) is None, table


def test_migrating_leaves_the_process_loggers_enabled(scratch: tuple[Config, str]) -> None:
    """``cli migrations`` and this suite migrate in process. Configured with ``fileConfig``'s default, env.py
    disabled every logger that existed already, so a module's warnings went silent from then on."""
    config, _ = scratch
    existing = logging.getLogger("tests.migrations.existing_logger")
    command.upgrade(config, "heads")

    assert not existing.disabled


def test_grant_migration_keeps_existing_turns_unverified(scratch: tuple[Config, str]) -> None:
    config, url = scratch
    command.upgrade(config, "f491e66e47d3")
    async def previous_connector_cache():
        from sqlalchemy import MetaData, Table
        from db.models.mail_account import MailAccount
        from db.models.mail_message import MailMessage
        account = MailAccount(provider='gmail', auth_type='mistral_connector', email_address='synthetic@example.test')
        mail = MailMessage(id='previous-mail', account_id=account.id, folder='ARCHIVE', provider_uid='1')
        engine = create_async_engine(url)
        try:
            async with engine.begin() as conn:
                def insert_existing(connection):
                    for model in (account, mail):
                        table = Table(model.__tablename__, MetaData(), autoload_with=connection)
                        values = {col.name: getattr(model, col.name) for col in table.c if col.computed is None}
                        connection.execute(table.insert().values(**values))
                await conn.run_sync(insert_existing)
        finally:
            await engine.dispose()
    asyncio.run(previous_connector_cache())
    asyncio.run(_admin_on(url, """
        INSERT INTO chat_context (id, conversation_id, app_prompt_version, account_scope_json, revoked)
        VALUES ('previous-turn', 'previous-chat', '9', '{"account_ids": ["previous-account"], "selection": null}', false)
    """))
    command.upgrade(config, "heads")
    preserved = asyncio.run(_scalar(url, """
        SELECT count(*) FROM chat_context WHERE id = 'previous-turn' AND mail_scope_version IS NULL
    """))
    assert preserved == 1
    assert asyncio.run(_scalar(url, "SELECT count(*) FROM chat_settings")) == 0
    assert asyncio.run(_scalar(url, "SELECT unverified_connector FROM mail_message WHERE id='previous-mail'")) is True


def test_calendar_upgrade_keeps_unverified_retries_blocked(scratch):
    config, url = scratch
    command.upgrade(config, "9c647152d2eb")
    asyncio.run(_admin_on(url, """
        INSERT INTO calendar_source (id, provider, connection_ref, external_id, name, timezone, capabilities_json, is_active)
        SELECT id, 'google', 'synthetic', id, id, 'UTC', '["read"]', true
        FROM unnest(ARRAY['verified', 'stopped', 'queued']) AS id
    """))
    asyncio.run(_admin_on(url, """
        INSERT INTO calendar_sync_state (source_id, incomplete, last_success_at, last_validated_at, last_checked_at, last_error)
        SELECT id, false, now() - interval '1 day', now() - interval '1 day',
               CASE WHEN id = 'queued' THEN now() ELSE now() - interval '1 day' END,
               CASE WHEN id = 'stopped' THEN 'reconnect_required' ELSE NULL END FROM calendar_source
    """))
    command.upgrade(config, "heads")
    assert asyncio.run(_scalar(url, """
        SELECT array_agg(source_id ORDER BY source_id) FROM calendar_sync_state WHERE access_blocked
    """)) == ['queued', 'stopped']
